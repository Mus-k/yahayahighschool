/**
 * Get a translation for a given English key string in the target locale.
 * Falls back to the original string if no translation found.
 */
export function t(key: string, locale: string): string {
  if (locale === 'en' || !locale) return key;
  const dict = i18nDict[locale as SupportedLocale];
  if (!dict) return key;
  const clean = key.trim().toLowerCase().replace(/\s+/g, ' ');
  return dict[clean] ?? dict[clean.replace(/\.$/, '')] ?? key;
}
